import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage();
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
await page.goto('http://localhost:3333/demos/social/campaign-landing');
await page.waitForSelector('text=Mends from March 2026');
const out = {};
await page.getByRole('button', { name: 'Ceramics', exact: true }).click();
await page.waitForTimeout(100);
out.anims = await page.evaluate(() => document.getAnimations().length);
out.count = await page.locator('text=/Showing \\d+ of 12 mends/').textContent();
out.visibleTiles = await page.locator('[data-tile]:visible').count();
await page.getByRole('button', { name: 'All', exact: true }).click();
// form: submit empty → errors + focus
await page.getByRole('button', { name: 'Pledge my mend' }).click();
out.focusAfterBadSubmit = await page.evaluate(() => document.activeElement?.id?.endsWith('-item'));
out.errorTexts = await page.locator('[aria-invalid="true"]').count();
out.status = await page.locator('form [role=status]').textContent();
await page.getByLabel('What will you mend?').fill('lamp');
await page.getByLabel('What will you mend?').blur();
await page.locator('label').filter({ hasText: /^Electronics$/ }).last().click();
await page.getByLabel('Where will you mend it?').selectOption('Canal Street café');
await page.getByLabel(/Show my before-and-after/).check();
await page.getByRole('button', { name: 'Pledge my mend' }).click();
await page.waitForTimeout(900);
out.doneFocus = await page.evaluate(() => document.activeElement?.textContent);
out.cardLabel = await page.locator('canvas[role=img]').getAttribute('aria-label');
// share card download
const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 5000 }).catch(() => null), page.getByRole('button', { name: 'Download PNG' }).click()]);
out.download = dl ? dl.suggestedFilename() : null;
// leaderboard
await page.getByRole('button', { name: 'Play March' }).click();
await page.waitForTimeout(4000);
out.weekChecked = await page.locator('input[type=radio]:checked').evaluateAll((els) => els.map((e) => e.parentElement?.textContent));
out.rankList = await page.locator('ol[aria-label^="Cafés ranked"] li').first().textContent();
out.errors = errors;
console.log(JSON.stringify(out, null, 1));
await browser.close();
