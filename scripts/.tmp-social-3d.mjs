import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage();
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
const reqs = [];
page.on('request', (r) => { if (r.url().includes('/models/')) reqs.push(r.url().split('/models/')[1]); });
await page.goto('http://localhost:3333/demos/social/3d-social-post');
await page.waitForSelector('text=Interact in 3D');
await page.waitForTimeout(800);
const out = { beforeRequests: [...reqs], canvasesBefore: await page.locator('canvas').count() };
await page.getByRole('button', { name: /Interact in 3D/ }).click();
out.focusAfterOpen = await page.evaluate(() => document.activeElement?.textContent);
await page.waitForSelector('[data-live]', { timeout: 20000 });
out.canvases = await page.locator('canvas').count();
out.afterRequests = [...reqs];
const d0 = await page.evaluate(() => window.__STUDIO3_3D__?.frames ?? 0);
await page.getByRole('button', { name: 'Turn left' }).click();
await page.waitForTimeout(400);
out.framesAdvancedOnTurn = (await page.evaluate(() => window.__STUDIO3_3D__?.frames ?? 0)) > d0;
out.az = await page.locator('text=/AZ \\d{3}°/').textContent();
await page.getByRole('button', { name: 'Spin' }).click();
await page.waitForTimeout(600);
out.spinPressed = await page.getByRole('button', { name: 'Spin' }).getAttribute('aria-pressed');
out.diag = await page.evaluate(() => { const d = window.__STUDIO3_3D__; return d && { calls: d.renderer.calls, triangles: d.renderer.triangles, frameloop: d.frameloop, quality: d.quality }; });
await page.getByRole('button', { name: 'Spin' }).click();
await page.screenshot({ path: process.argv[2] });
await page.getByRole('button', { name: 'Close 3D' }).click();
await page.waitForTimeout(300);
out.canvasesAfterClose = await page.locator('canvas').count();
out.focusAfterClose = await page.evaluate(() => document.activeElement?.textContent);
out.errors = errors;
console.log(JSON.stringify(out, null, 1));
await browser.close();
