import { chromium } from 'playwright';
const out = '/tmp/claude-0/-home-user/77865dc0-1700-59d0-bb68-e0d68f61d45b/scratchpad/spatial/';
const dark = process.argv.includes('--dark');
const b = await chromium.launch({ args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 1100, height: 900 }, colorScheme: dark ? 'dark' : 'light' });
const errors = [];
p.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
p.on('pageerror', (e) => errors.push('pageerror ' + e.message));
await p.goto('http://localhost:3333/effects/dot-grid-pointer-field');
const field = p.locator('[data-effect-stage="dot-grid-pointer-field"] [role="application"]');
await field.waitFor();
await p.waitForTimeout(800);
const box = await field.boundingBox();
// count rAF callbacks to prove the loop stops at rest
await p.evaluate(() => { window.__raf = 0; const o = window.requestAnimationFrame; window.requestAnimationFrame = (cb) => o((t) => { window.__raf++; cb(t); }); });
await p.mouse.move(box.x + box.width * 0.3, box.y + box.height * 0.5);
await p.mouse.move(box.x + box.width * 0.45, box.y + box.height * 0.45, { steps: 8 });
await p.waitForTimeout(120);
await p.mouse.down(); await p.mouse.up();
await p.waitForTimeout(380);
await p.screenshot({ path: out + `dots-active${dark ? '-dark' : ''}.png`, clip: { x: box.x, y: box.y, width: box.width, height: box.height + 70 } });
await p.waitForTimeout(2500);
const a = await p.evaluate(() => window.__raf);
await p.waitForTimeout(1000);
const c = await p.evaluate(() => window.__raf);
console.log('rAF calls during 1s at rest (pointer still inside, static):', c - a);
await p.mouse.move(5, 5);
await p.waitForTimeout(2500);
const d = await p.evaluate(() => window.__raf);
await p.waitForTimeout(1000);
console.log('rAF calls during 1s after leaving:', (await p.evaluate(() => window.__raf)) - d);
// keyboard
await p.locator('[data-replay]').focus();
await p.keyboard.press('Tab');
console.log('focused:', await p.evaluate(() => document.activeElement?.getAttribute('aria-label')));
await p.keyboard.press('ArrowRight'); await p.keyboard.press('ArrowRight'); await p.keyboard.press('Shift+ArrowUp');
await p.waitForTimeout(150);
await p.keyboard.press('Enter');
await p.waitForTimeout(300);
await p.screenshot({ path: out + `dots-kbd${dark ? '-dark' : ''}.png`, clip: { x: box.x, y: box.y, width: box.width, height: box.height + 70 } });
await p.keyboard.press('Escape');
await p.keyboard.press('Tab');
console.log('next focus:', await p.evaluate(() => document.activeElement?.textContent));
console.log('errors', errors);
await b.close();
