import { chromium } from 'playwright';
const S = '/tmp/claude-0/-home-user/77865dc0-1700-59d0-bb68-e0d68f61d45b/scratchpad/rb';
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await (await b.newContext({ viewport: { width: 1000, height: 900 } })).newPage();
const errors = [];
p.on('console', (m) => { if (m.type() === 'error') errors.push(m.text().slice(0, 160)); });
p.on('pageerror', (e) => errors.push('pageerror ' + e.message.slice(0, 160)));
await p.goto('http://localhost:3333/effects/skeleton-shimmer-handoff');
const stage = p.locator('[data-effect-stage="skeleton-shimmer-handoff"]');
const list = stage.locator('ul');
await list.waitFor();
await p.waitForTimeout(500);
const rows = () => list.evaluate((ul) => [...ul.children].map((li) => Math.round(li.getBoundingClientRect().height * 100) / 100));
const st = async () => ({ busy: await list.getAttribute('aria-busy'), status: await stage.locator('[role=status]').textContent(), clip: await stage.evaluate((s) => (s.querySelector('[class*=shimmer]')?.style.clipPath ?? 'none').slice(0, 40)) });
const loadingRows = await rows();
console.log('loading rows', loadingRows, JSON.stringify(await st()));
await stage.screenshot({ path: `${S}/skel-a.png` });
await p.waitForTimeout(2200);
const readyRows = await rows();
console.log('ready rows  ', readyRows, JSON.stringify(await st()), 'shift', loadingRows.map((h, i) => +(readyRows[i] - h).toFixed(2)));
await stage.screenshot({ path: `${S}/skel-b.png` });
// keyboard reload
await stage.getByRole('button', { name: 'Reload' }).focus();
await p.keyboard.press('Enter');
await p.waitForTimeout(80);
console.log('after Enter', JSON.stringify(await st()), 'aria-disabled', await stage.getByRole('button', { name: 'Reload' }).getAttribute('aria-disabled'));
await p.keyboard.press('Space'); // ignored while busy
await p.waitForTimeout(2300);
console.log('reloaded', JSON.stringify(await st()), await list.locator('h4').first().textContent(), 'focus', await p.evaluate(() => document.activeElement?.textContent?.trim()));
console.log('errors', errors);
await b.close();
