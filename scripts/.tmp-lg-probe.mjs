import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 1000 } });
const errors = [];
p.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.type() + ': ' + m.text().slice(0, 400)); });
p.on('pageerror', (e) => errors.push('pageerror ' + e.message.slice(0, 400)));
await p.goto('http://localhost:3333' + process.argv[2]);
await p.waitForTimeout(4000);
console.log(await p.evaluate((sel) => document.querySelector(sel)?.innerText.slice(0, 400), `[data-effect-stage]`));
console.log(errors.slice(0, 6));
await b.close();
